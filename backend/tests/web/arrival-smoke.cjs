const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_EXECUTABLE || chromium.executablePath()});
 const page=await browser.newPage({viewport:{width:390,height:844}}), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8766/web/');
 await page.evaluate(()=>localStorage.setItem('trip-planner.web.v1',JSON.stringify([{id:'trip',title:'Round trip',revision:0,startId:'a',endId:'a',plan:null,places:[{id:'a',name:'Home',address:'',latitude:32.06,longitude:34.77},{id:'b',name:'Stop',address:'',latitude:32.068,longitude:34.778}]}])));
 await page.reload();await page.getByRole('button',{name:'Round trip',exact:false}).click();
 await page.locator('nav [data-view=plan]').click();
 let count=0, request;
 await page.route('**/v1/routes/optimize',async route=>{request=route.request().postDataJSON();count++;await route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({error:{code:'location_not_routable',locationIds:['start','end']}})});});
 await page.locator('[data-action=optimize]').click();
 await page.getByRole('alert').filter({hasText:'nearby driving road for Home'}).waitFor();
 await page.locator('[data-arrival=a]').click();
 await page.getByLabel('Arrival latitude',{exact:true}).fill('32.061');
 await page.getByLabel('Arrival longitude',{exact:true}).fill('34.771');
 await page.getByRole('button',{name:'Use this arrival point',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('dialog[open]'));
 await page.getByText('Arrival point adjusted',{exact:false}).waitFor();
 await page.waitForTimeout(300);
 if(count!==2 || request.start.latitude!==32.061 || request.end.latitude!==32.061)throw Error('round-trip arrival not applied');
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('trip-planner.web.v1'))[0]);
 if(saved.places[0].latitude!==32.06)throw Error('original overwritten');
 await page.locator('[data-arrival=a]').click();
 if(await page.getByLabel('Arrival latitude',{exact:true}).inputValue()!=='32.061')throw Error('failed retry lost arrival');
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await page.screenshot({path:process.env.ARRIVAL_SCREENSHOT || 'arrival-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('mobile overflow');
 await page.locator('[data-reset-arrival=a]').click();
 if((await page.evaluate(()=>JSON.parse(localStorage.getItem('trip-planner.web.v1'))[0])).places[0].arrival)throw Error('reset failed');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: failed-place identification, arrival editor, round-trip override, preserved original, failed retry retention, reset, mobile layout');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
